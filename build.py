#!/usr/bin/env python3
"""Assemble providers/*.js from src/, and hold the manifest to the tree.

Standard library only, and no npm: the whole build is concatenation.  Each
generated file is committed, because that is the file a Nuvio client downloads -
so what people actually run is reviewable in the history rather than produced on
the fly.  `--check` re-runs the build without writing and fails if anything is
out of step, which is what stops src/ and providers/ drifting apart.

Why concatenate instead of keeping six self-contained copies of common.js:
Nuvio evaluates exactly one file per scraper, in a fresh QuickJS runtime, with
no module graph to hang a shared library off.  Copying the shared half into six
files would be ~1500 lines that drift, and a matcher fix would become six edits.

The manifest is the registry - it is what says which providers exist, and the
build refuses to run when it and src/ disagree.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
OUT = ROOT / "providers"
MANIFEST = ROOT / "manifest.json"

BANNER = """\
// {filename} - GENERATED by build.py from src/common.js + src/{sid}.js.
//
// Do not edit this file.  The next build overwrites it and `python build.py
// --check` fails while it is out of step with src/ - edit the two sources and
// rebuild.
//
// Concatenated rather than imported because Nuvio evaluates one file per
// scraper in a fresh QuickJS runtime, so there is no module to share.

"""

FOOTER = """

// Nuvio looks for module.exports.getStreams first and globalThis.getStreams
// second; the wrapper that puts `module` in scope is the host's, not this
// file's.
module.exports = {{ getStreams: getStreams }};
"""

REQUIRED_TOP = ("name", "version", "scrapers")
REQUIRED_SCRAPER = ("id", "name", "version", "filename", "supportedTypes")


def die(msg: str) -> "None":
    sys.stderr.write(f"build.py: {msg}\n")
    raise SystemExit(1)


def load_manifest() -> dict:
    try:
        manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    except FileNotFoundError:
        die("manifest.json is missing")
    except json.JSONDecodeError as e:
        die(f"manifest.json is not valid JSON: {e}")

    for key in REQUIRED_TOP:
        if not manifest.get(key):
            die(f"manifest.json has no {key!r}")
    if not isinstance(manifest["scrapers"], list):
        die("manifest.json: 'scrapers' must be a list")

    seen_ids, seen_files = set(), set()
    for i, scraper in enumerate(manifest["scrapers"]):
        where = f"scrapers[{i}]"
        for key in REQUIRED_SCRAPER:
            if not scraper.get(key):
                die(f"{where} has no {key!r}")
        sid = scraper["id"]
        where = f"scrapers[{i}] ({sid})"
        if sid in seen_ids:
            die(f"{where}: duplicate id")
        if scraper["filename"] in seen_files:
            die(f"{where}: duplicate filename {scraper['filename']!r}")
        seen_ids.add(sid)
        seen_files.add(scraper["filename"])

        # The file Nuvio fetches is resolved from the manifest URL + filename,
        # so a filename with a directory in it would resolve somewhere else.
        if "/" in scraper["filename"] or not scraper["filename"].endswith(".js"):
            die(f"{where}: filename must be a bare *.js name")

        types = scraper["supportedTypes"]
        if not isinstance(types, list) or not types:
            die(f"{where}: supportedTypes must be a non-empty list")
        for t in types:
            if t not in ("movie", "tv"):
                die(f"{where}: supportedTypes has {t!r}, "
                    "which is neither 'movie' nor 'tv'")

        if not (SRC / f"{sid}.js").exists():
            die(f"{where}: src/{sid}.js does not exist")

    return manifest


def render(manifest: dict) -> dict:
    """{filename: file text} for every scraper in the manifest."""
    common = (SRC / "common.js").read_text(encoding="utf-8").rstrip() + "\n"
    out = {}
    for scraper in manifest["scrapers"]:
        sid = scraper["id"]
        body = (SRC / f"{sid}.js").read_text(encoding="utf-8").rstrip() + "\n"
        out[scraper["filename"]] = (
            BANNER.format(filename=scraper["filename"], sid=sid)
            + common + "\n" + body + FOOTER.format()
        )
    return out


def main(argv: list) -> int:
    check = "--check" in argv[1:]
    manifest = load_manifest()
    generated = render(manifest)

    if check:
        drift = []
        for name, text in sorted(generated.items()):
            path = OUT / name
            if not path.exists():
                drift.append(f"missing:     providers/{name}")
            elif path.read_text(encoding="utf-8") != text:
                drift.append(f"out of date: providers/{name}")
        for path in sorted(OUT.glob("*.js")) if OUT.is_dir() else []:
            if path.name not in generated:
                drift.append(f"stale:       providers/{path.name}")
        if drift:
            sys.stderr.write(
                "build.py: providers/ is not what src/ produces:\n  "
                + "\n  ".join(drift)
                + "\nRun `python build.py` and commit the result.\n"
            )
            return 1
        print(f"providers/ is up to date ({len(generated)} files)")
        return 0

    OUT.mkdir(exist_ok=True)
    for name, text in sorted(generated.items()):
        (OUT / name).write_text(text, encoding="utf-8")
    removed = []
    for path in sorted(OUT.glob("*.js")):
        if path.name not in generated:
            path.unlink()
            removed.append(path.name)

    total = sum(len(t.splitlines()) for t in generated.values())
    print(f"wrote {len(generated)} providers ({total} lines) from "
          f"{len(manifest['scrapers'])} manifest entries")
    for name in removed:
        print(f"removed providers/{name} (no longer in the manifest)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
